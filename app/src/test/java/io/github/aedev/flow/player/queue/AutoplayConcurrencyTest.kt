package io.github.aedev.flow.player.queue

import io.github.aedev.flow.data.music.model.MusicTrack
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test

class AutoplayConcurrencyTest {
    private lateinit var coordinator: HybridMusicQueueCoordinator

    private fun track(id: String): MusicTrack =
        MusicTrack(
            videoId = id,
            title = "Track $id",
            artist = "Artist $id",
            thumbnailUrl = "thumb_$id",
            duration = 180,
        )

    @Before
    fun setup() {
        coordinator = HybridMusicQueueCoordinator()
    }

    /**
     * Scenario A: Playlist Switch During In-Flight Fetch
     * A recommendation request is triggered for Playlist A (captured sessionId = S1).
     * Before results arrive, user switches to Playlist B (new sessionId = S2).
     * Old request returns with S1.
     * Expected: Results tagged with S1 must be rejected and never enter Playlist B.
     */
    @Test
    fun `scenario A - playlist switch during fetch discards results from previous session`() {
        val playlistA = listOf(track("A1"), track("A2"))
        coordinator.loadSource(
            source = PlaybackSourceInfo(type = QueueSource.PLAYLIST, id = "pl_A", title = "Playlist A"),
            tracks = playlistA,
            startIndex = 0,
        )

        val sessionAId = coordinator.session.value.id

        // In flight recommendations fetched for Playlist A
        val inFlightRecommendationsA = listOf(track("AutoA1"), track("AutoA2"))

        // User switches to Playlist B before A finishes
        val playlistB = listOf(track("B1"), track("B2"), track("B3"))
        coordinator.loadSource(
            source = PlaybackSourceInfo(type = QueueSource.PLAYLIST, id = "pl_B", title = "Playlist B"),
            tracks = playlistB,
            startIndex = 0,
        )

        val sessionBId = coordinator.session.value.id
        assertNotEquals(sessionAId, sessionBId)

        // Session ID check guard: if session ID does not match current session, discard
        val currentSessionId = coordinator.session.value.id
        if (sessionAId == currentSessionId) {
            coordinator.appendAutoplayBatch(inFlightRecommendationsA)
        }

        // Verify Playlist B remains pure and contains no tracks from Playlist A recommendations
        assertEquals(listOf("B1", "B2", "B3"), coordinator.queue.value.map { it.videoId })
        assertEquals(0, coordinator.queueEntries.value.count { it.source == QueueSource.AUTOPLAY })
    }

    /**
     * Scenario B: Autoplay Disabled During In-Flight Fetch
     * Autoplay fetch begins.
     * User toggles autoplay OFF in UI before results return.
     * Expected: No autoplay entries are committed into the active queue.
     */
    @Test
    fun `scenario B - autoplay disabled during fetch prevents appending recommendations`() {
        val tracks = listOf(track("1"), track("2"))
        coordinator.loadSource(
            source = PlaybackSourceInfo(type = QueueSource.ALBUM, title = "Album"),
            tracks = tracks,
            startIndex = 0,
        )

        assertTrue(coordinator.autoplayEnabled.value)

        // User turns off autoplay while request is in flight
        coordinator.setAutoplayEnabled(false)
        assertFalse(coordinator.autoplayEnabled.value)

        // Guard check: do not append if autoplay was disabled
        val candidates = listOf(track("Auto1"), track("Auto2"))
        if (coordinator.autoplayEnabled.value) {
            coordinator.appendAutoplayBatch(candidates)
        }

        assertEquals(listOf("1", "2"), coordinator.queue.value.map { it.videoId })
        assertEquals(0, coordinator.queueEntries.value.count { it.source == QueueSource.AUTOPLAY })
    }

    /**
     * Scenario C: Queue Changes During Fetch
     * Autoplay request is initiated.
     * Before it commits, user adds manual tracks via Play Next and Add to Queue.
     * When autoplay batch returns:
     * Expected:
     * - User-added tracks remain ahead of autoplay items.
     * - Autoplay deduplicates against the mutated queue and history.
     */
    @Test
    fun `scenario C - queue mutations during fetch maintain user priority and deduplication`() {
        val tracks = listOf(track("A"), track("B"))
        coordinator.loadSource(
            source = PlaybackSourceInfo(type = QueueSource.PLAYLIST, title = "Playlist"),
            tracks = tracks,
            startIndex = 0,
        )

        // Candidates generated by MusicBrain based on A
        val rawCandidates = listOf(track("UserNext"), track("AutoC1"), track("B"))

        // User acts before candidates land:
        coordinator.playNext(track("UserNext"))
        coordinator.addToUserQueue(track("UserManual"))

        // Current queue is now: A -> UserNext -> B -> UserManual
        assertEquals(listOf("A", "UserNext", "B", "UserManual"), coordinator.queue.value.map { it.videoId })

        // When candidates arrive, coordinator appends them
        val appended = coordinator.appendAutoplayBatch(rawCandidates)

        // UserNext and B are already in the active queue, so only AutoC1 is accepted
        assertEquals(listOf("AutoC1"), appended.map { it.track.videoId })

        // Expected final order: A -> UserNext -> B -> UserManual -> AutoC1
        assertEquals(listOf("A", "UserNext", "B", "UserManual", "AutoC1"), coordinator.queue.value.map { it.videoId })

        val entries = coordinator.queueEntries.value
        assertEquals(QueueSource.PLAY_NEXT, entries[1].source)
        assertEquals(QueueSource.MANUAL_QUEUE, entries[3].source)
        assertEquals(QueueSource.AUTOPLAY, entries[4].source)
    }

    /**
     * Scenario D: Multiple Refill Triggers
     * Rapid repeated calls to appendAutoplayBatch with overlapping tracks.
     * Expected: Duplicate candidates are rejected; queue size only grows by distinct new tracks.
     */
    @Test
    fun `scenario D - multiple rapid refill triggers reject duplicates and do not inflate queue`() {
        val tracks = listOf(track("1"))
        coordinator.loadSource(
            source = PlaybackSourceInfo(type = QueueSource.SINGLE_TRACK, title = "Single"),
            tracks = tracks,
            startIndex = 0,
        )

        val batch1 = listOf(track("Auto1"), track("Auto2"))
        val firstAppend = coordinator.appendAutoplayBatch(batch1)
        assertEquals(2, firstAppend.size)

        // Second trigger tries to add the same items again
        val secondAppend = coordinator.appendAutoplayBatch(batch1)
        assertEquals(0, secondAppend.size)

        // Queue size remains exactly 3: [1, Auto1, Auto2]
        assertEquals(listOf("1", "Auto1", "Auto2"), coordinator.queue.value.map { it.videoId })
    }
}
